/* Voyager companion — notifications Worker (2.23.0). Runs on Cloudflare beside the static site.

   What it does
     · Viewers who turn notifications on in the companion are stored as Web Push subscriptions in a KV namespace
       (binding PUSH): the browser's push address and keys, the topics they chose and, for "you won", the card name they
       picked. Nothing else — no account, no e-mail, no IP address.
     · Once a minute (cron) it reads the public feed (the same feed.json the site reads) and compares it with what it saw
       last time. Going on air, a Dreadnought boarding, a newly opened giveaway and a newly confirmed winner each become
       one notification to the viewers who asked for that topic. The Voyager app is never contacted and needs no key:
       the feed can only be written by the streamer's own GitHub token, so it is the trusted signal.
     · The signing keys (VAPID) are generated by the Worker on first use and kept in the same KV namespace.

   Free-plan limits: a Worker invocation may make 50 outside requests, so sends go out 40 at a time and the Worker calls
   itself (service binding SELF) for the next batch; without that binding the rest follows on the next cron ticks. */

export const TOPICS={live:'l',dread:'d',giveaway:'g',win:'w'};
const BATCH=40,MAX_SUBS=5000,STALE_MS=5*60000,LIVE_COOLDOWN_MS=3*3600000,DREAD_COOLDOWN_MS=8*60000;
const PUSH_HOSTS=/(^|\.)(fcm\.googleapis\.com|push\.apple\.com|push\.services\.mozilla\.com|notify\.windows\.com)$/i;
const enc=new TextEncoder();
const b64u=buf=>{let s='';for(const b of new Uint8Array(buf))s+=String.fromCharCode(b);return btoa(s).replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'');};
const unb64u=str=>{const s=String(str).replace(/-/g,'+').replace(/_/g,'/');const bin=atob(s+'==='.slice((s.length+3)%4));const out=new Uint8Array(bin.length);for(let i=0;i<bin.length;i++)out[i]=bin.charCodeAt(i);return out;};
const concat=(...parts)=>{const out=new Uint8Array(parts.reduce((n,p)=>n+p.length,0));let o=0;for(const p of parts){out.set(p,o);o+=p.length;}return out;};
const json=(data,status=200)=>new Response(JSON.stringify(data),{status,headers:{'content-type':'application/json; charset=utf-8','cache-control':'no-store'}});
const clean=(v,max)=>String(v??'').replace(/[\u0000-\u001f\u007f]/g,' ').replace(/\s+/g,' ').trim().slice(0,max);
async function sha(text){return [...new Uint8Array(await crypto.subtle.digest('SHA-256',enc.encode(text)))].map(b=>b.toString(16).padStart(2,'0')).join('');}

// ---------- VAPID (RFC 8292) ----------
export async function vapidKeys(env){
  const saved=await env.PUSH.get('vapid','json');if(saved?.publicKey&&saved?.privateJwk)return saved;
  const pair=await crypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},true,['sign','verify']);
  const keys={publicKey:b64u(await crypto.subtle.exportKey('raw',pair.publicKey)),privateJwk:await crypto.subtle.exportKey('jwk',pair.privateKey)};
  await env.PUSH.put('vapid',JSON.stringify(keys));return keys;
}
export async function vapidHeader(keys,endpoint,subject,now=Date.now()){
  const head=b64u(enc.encode(JSON.stringify({typ:'JWT',alg:'ES256'}))),body=b64u(enc.encode(JSON.stringify({aud:new URL(endpoint).origin,exp:Math.floor(now/1000)+12*3600,sub:subject})));
  const key=await crypto.subtle.importKey('jwk',keys.privateJwk,{name:'ECDSA',namedCurve:'P-256'},false,['sign']);
  const sig=await crypto.subtle.sign({name:'ECDSA',hash:'SHA-256'},key,enc.encode(head+'.'+body));
  return 'vapid t='+head+'.'+body+'.'+b64u(sig)+', k='+keys.publicKey;
}
// ---------- message encryption (RFC 8291, aes128gcm) ----------
async function hkdf(salt,ikm,info,len){const key=await crypto.subtle.importKey('raw',ikm,'HKDF',false,['deriveBits']);return new Uint8Array(await crypto.subtle.deriveBits({name:'HKDF',hash:'SHA-256',salt,info},key,len*8));}
export async function encryptPush(sub,text,{salt=crypto.getRandomValues(new Uint8Array(16)),local=null}={}){
  const uaPublic=unb64u(sub.p),auth=unb64u(sub.a);
  const pair=local||await crypto.subtle.generateKey({name:'ECDH',namedCurve:'P-256'},true,['deriveBits']);
  const asPublic=new Uint8Array(await crypto.subtle.exportKey('raw',pair.publicKey));
  const uaKey=await crypto.subtle.importKey('raw',uaPublic,{name:'ECDH',namedCurve:'P-256'},false,[]);
  const shared=new Uint8Array(await crypto.subtle.deriveBits({name:'ECDH',public:uaKey},pair.privateKey,256));
  const ikm=await hkdf(auth,shared,concat(enc.encode('WebPush: info\0'),uaPublic,asPublic),32);
  const cek=await hkdf(salt,ikm,enc.encode('Content-Encoding: aes128gcm\0'),16),nonce=await hkdf(salt,ikm,enc.encode('Content-Encoding: nonce\0'),12);
  const key=await crypto.subtle.importKey('raw',cek,'AES-GCM',false,['encrypt']);
  const body=new Uint8Array(await crypto.subtle.encrypt({name:'AES-GCM',iv:nonce},key,concat(enc.encode(text),new Uint8Array([2]))));
  const rs=new Uint8Array([0,0,16,0]); // record size 4096
  return concat(salt,rs,new Uint8Array([asPublic.length]),asPublic,body);
}
// One notification to one subscription. Returns the push service's status (404/410 = the subscription is gone).
export async function sendPush(env,keys,sub,payload,fetcher=fetch){
  try{const body=await encryptPush(sub,JSON.stringify(payload));
    const r=await fetcher(sub.e,{method:'POST',headers:{authorization:await vapidHeader(keys,sub.e,env.SUBJECT||'https://voyagercommand.com'),'content-encoding':'aes128gcm','content-type':'application/octet-stream',ttl:String(payload.ttl||600),urgency:'high',...(payload.tag?{topic:String(payload.tag).replace(/[^A-Za-z0-9_-]/g,'').slice(0,32)}:{})},body});
    return r.status;}catch{return 0;}
}

// ---------- subscriptions (KV) ----------
export function validSubscription(s){
  const e=String(s?.endpoint||''),p=String(s?.keys?.p256dh||''),a=String(s?.keys?.auth||'');
  let host='';try{const u=new URL(e);if(u.protocol!=='https:')return null;host=u.hostname;}catch{return null;}
  if(!PUSH_HOSTS.test(host)||e.length>600||!/^[A-Za-z0-9_-]{80,100}$/.test(p)||!/^[A-Za-z0-9_-]{16,32}$/.test(a))return null;
  return {e,p,a};
}
export const topicLetters=list=>[...new Set((Array.isArray(list)?list:[]).map(t=>TOPICS[t]).filter(Boolean))].join('');
async function allSubs(env){const out=[];let cursor;do{const page=await env.PUSH.list({prefix:'sub:',cursor,limit:1000});for(const k of page.keys)if(k.metadata?.e)out.push({key:k.name,...k.metadata});cursor=page.list_complete?undefined:page.cursor;}while(cursor);return out;}
export const wants=(sub,event)=>String(sub.t||'').includes(TOPICS[event.topic])&&(!event.names||(!!sub.n&&event.names.includes(sub.n)));

// ---------- sending an event to everyone who asked for it ----------
export async function drain(env,event,from=0,fetcher=fetch){
  const keys=await vapidKeys(env),targets=(await allSubs(env)).filter(s=>wants(s,event)).sort((a,b)=>a.key<b.key?-1:1),batch=targets.slice(from,from+BATCH);
  const results=await Promise.all(batch.map(s=>sendPush(env,keys,s,event.payload,fetcher)));
  await Promise.all(batch.map((s,i)=>results[i]===404||results[i]===410?env.PUSH.delete(s.key):null));
  const next=from+BATCH,sent=results.filter(r=>r>=200&&r<300).length;
  if(next<targets.length){
    if(env.SELF){const secret=await drainSecret(env);await env.SELF.fetch('https://self/api/push/drain',{method:'POST',headers:{'content-type':'application/json','x-voyager-drain':secret},body:JSON.stringify({event,from:next})});}
    else await env.PUSH.put('job',JSON.stringify({event,from:next,at:Date.now()}),{expirationTtl:900});
  }else await env.PUSH.delete('job');
  return {targets:targets.length,sent,from,next:next<targets.length?next:null};
}
async function drainSecret(env){let s=await env.PUSH.get('drain-secret');if(!s){s=b64u(crypto.getRandomValues(new Uint8Array(24)));await env.PUSH.put('drain-secret',s);}return s;}

// ---------- what changed in the feed ----------
// state: what the last tick saw. Returns the next state and the events to send. The first tick only records.
export function diffFeed(feed,state,now=Date.now()){
  const fresh=!!feed&&feed.online!==false&&Number.isFinite(feed.generatedAt)&&now-feed.generatedAt<STALE_MS;
  const channel=clean(feed?.channel?.name,40)||'The stream',open=(feed?.giveaways||[]).filter(g=>g?.status==='open'&&g.id).map(g=>({id:String(g.id),title:clean(g.title,80),who:clean(g.eligibility,60)}));
  const winners=(feed?.winners||[]).filter(w=>w?.name&&w.at).map(w=>({key:w.at+':'+String(w.name).toLowerCase(),name:String(w.name).toLowerCase(),title:clean(w.title,80),at:w.at}));
  const next={seen:true,onAir:fresh&&!!feed.live?.onAir,phase:fresh?String(feed.dreadnought?.phase||''):'',open:open.map(g=>g.id),winAt:winners.reduce((m,w)=>Math.max(m,w.at),state?.winAt||0),liveAt:state?.liveAt||0,dreadAt:state?.dreadAt||0};
  const events=[];if(!state?.seen||!fresh)return {next:fresh?next:{...(state||{}),seen:!!state?.seen,onAir:false,phase:''},events};
  if(next.onAir&&!state.onAir&&now-(state.liveAt||0)>LIVE_COOLDOWN_MS){next.liveAt=now;events.push({topic:'live',payload:{title:channel+' is live',body:'Giveaways, the Dreadnought and your card — tap to open the companion.',url:'./#live',tag:'live',ttl:1800}});}
  if(['lobby','battle'].includes(next.phase)&&!['lobby','battle'].includes(state.phase||'')&&now-(state.dreadAt||0)>DREAD_COOLDOWN_MS){next.dreadAt=now;
    events.push({topic:'dread',payload:{title:'Dreadnought incoming!',body:next.phase==='lobby'?'Type !join in stream chat to board — the fight starts in moments.':'The fight is on — type !join in stream chat, then !fire.',url:'./#live',tag:'dread',ttl:300}});}
  for(const g of open)if(!(state.open||[]).includes(g.id))events.push({topic:'giveaway',payload:{title:'Giveaway open: '+g.title,body:(g.who?g.who+' · ':'')+'Enter in stream chat.',url:'./#giveaways',tag:'gw-'+g.id,ttl:1800}});
  for(const w of winners)if(w.at>(state.winAt||0)&&now-w.at<24*3600000)events.push({topic:'win',names:[w.name],payload:{title:'You won: '+w.title+'!',body:'Congratulations — check the stream or the Winners list for what happens next.',url:'./#winners',tag:'win-'+w.at,ttl:86400}});
  return {next,events:events.slice(0,8)};
}
export async function tick(env,fetcher=fetch,now=Date.now()){
  const job=await env.PUSH.get('job','json');if(job?.event){await drain(env,job.event,job.from||0,fetcher);return {resumed:true};}
  if(!env.FEED_URL)return {skipped:'no feed'};
  let feed=null;try{const r=await fetcher(env.FEED_URL+(env.FEED_URL.includes('?')?'&':'?')+'t='+Math.floor(now/30000),{cf:{cacheTtl:0}});if(r.ok)feed=await r.json();}catch{}
  if(!feed||feed.schema!==1)return {skipped:'feed unavailable'};
  const state=await env.PUSH.get('state','json'),{next,events}=diffFeed(feed,state,now);
  if(JSON.stringify(next)!==JSON.stringify(state))await env.PUSH.put('state',JSON.stringify(next));
  for(const e of events)await drain(env,e,0,fetcher);
  return {events:events.length};
}

// ---------- HTTP ----------
async function api(req,env,url){
  if(!env.PUSH)return json({message:'Notifications are not set up on this site.'},503);
  const path=url.pathname.replace(/\/+$/,'');
  if(path==='/api/push/key'&&req.method==='GET'){const k=await vapidKeys(env);return json({key:k.publicKey,topics:Object.keys(TOPICS)});}
  if(req.method!=='POST')return json({message:'Method not allowed.'},405);
  let body=null;try{const text=await req.text();if(text.length>4000)return json({message:'Too large.'},413);body=JSON.parse(text);}catch{return json({message:'Send JSON.'},400);}
  if(path==='/api/push/drain'){if(req.headers.get('x-voyager-drain')!==await drainSecret(env)||!body?.event?.payload)return json({message:'Not allowed.'},403);return json(await drain(env,body.event,Number(body.from)||0));}
  if(path==='/api/push/subscribe'){
    const s=validSubscription(body?.subscription);if(!s)return json({message:'That is not a push subscription this site accepts.'},400);
    const key='sub:'+(await sha(s.e)).slice(0,40),t=topicLetters(body.topics);
    if(!t){await env.PUSH.delete(key);return json({ok:true,topics:[]});}
    if(!(await env.PUSH.getWithMetadata(key)).metadata){const page=await env.PUSH.list({prefix:'sub:',limit:1000});if(page.keys.length>=1000&&(await allSubs(env)).length>=MAX_SUBS)return json({message:'The notification list is full.'},507);}
    await env.PUSH.put(key,'',{metadata:{...s,t,n:clean(body.name,60).toLowerCase(),at:Math.floor(Date.now()/1000)}});
    return json({ok:true,topics:Object.keys(TOPICS).filter(k=>t.includes(TOPICS[k]))});
  }
  if(path==='/api/push/unsubscribe'){const e=String(body?.endpoint||'');if(e)await env.PUSH.delete('sub:'+(await sha(e)).slice(0,40));return json({ok:true});}
  if(path==='/api/push/test'){ // a test notification to the caller's own subscription only
    const e=String(body?.endpoint||''),key='sub:'+(await sha(e)).slice(0,40),meta=(await env.PUSH.getWithMetadata(key)).metadata;if(!meta?.e)return json({message:'Turn notifications on first.'},404);
    const status=await sendPush(env,await vapidKeys(env),meta,{title:'Voyager notifications are on',body:'This is what an alert looks like. You choose which ones you get.',url:'./#more',tag:'test',ttl:120});
    if(status===404||status===410)await env.PUSH.delete(key);return json({ok:status>=200&&status<300,status},status>=200&&status<300?200:502);
  }
  return json({message:'Not found.'},404);
}
export default {
  async fetch(req,env){const url=new URL(req.url);if(url.pathname.startsWith('/api/push/'))return api(req,env,url).catch(e=>json({message:'Notifications are unavailable right now.'},500));return env.ASSETS.fetch(req);},
  async scheduled(event,env,ctx){ctx.waitUntil(tick(env).catch(()=>{}));}
};
